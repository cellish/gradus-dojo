// '3' / '3-2' / '8-2.5' -> {m,b} (0-based bar, 0-based beat)
function pos(at){const [bar,beat]=String(at).split('-');return {m:+bar-1,b:beat?+beat-1:0};}
function keyOf(at){const p=pos(at);return p.m+':'+p.b;}
// Assemble one example (optionally with a bad-example change) into slots and values.
function build(sp,ex,change){
  const cf=G.FUX_NOTES[CF_MODE],n=cf.length,rhythm=(ex.rhythm||[]).slice(),ties=(ex.ties||[]).slice();
  const S=G.buildSlots(sp,n,rhythm,ties),ed=S.filter(G.editable),toks=ex.cp.split(' ');
  if(ed.length!==toks.length)throw new Error(`lesson sp${sp} ${ex.title}: ${toks.length} notes for ${ed.length} slots`);
  const cp={};ed.forEach((s,k)=>{if(toks[k]!=='-')cp[G.skey(s)]=G.N(toks[k]);});
  const changed=[];
  if(change)for(const [at,nm] of Object.entries(change)){const k=keyOf(at);
    if(!S.some(s=>G.skey(s)===k&&G.editable(s)))throw new Error(`lesson sp${sp}: no editable slot at ${at}`);
    cp[k]=G.N(nm);changed.push(S.findIndex(s=>G.skey(s)===k));}
  const vals=G.valsOf(S,cp);
  return {sp,cf,above:ex.above,slots:S,vals,rhythm,ties,cp,changed};
}
